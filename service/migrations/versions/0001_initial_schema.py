"""Initial Keystone schema: landing, staging, identity, invariants, review, ops.

Revision ID: 0001_initial_schema
Revises:
Create Date: 2026-08-22

Hand-written, not autogenerated. Notes on the choices that are load-bearing
rather than incidental:

* **Extensions.** ``vector`` (incident similarity) and ``pgcrypto`` (SQL-side
  digest, used by the schema tests to cross-check the API-key hashing scheme)
  are created here, so ``alembic upgrade head`` on a *completely empty*
  database is sufficient. ``infra/initdb`` also creates them on first boot;
  both are ``IF NOT EXISTS``.

* **No unique key on ``(generation, natural_key)`` in the ``stg_*`` tables.**
  Staging mirrors what a source actually emitted, and the conflict catalogue
  requires duplicates to be *representable*: C11 is literally "the same
  ``payment_id`` twice in one generation". A unique constraint there would make
  the mandated conflict unstorable, so those are plain indexes.

* **``entity_links``/``field_lineage`` carry ``canonical_id`` without a foreign
  key to ``entities``.** ``canonical_id`` is a deterministic uuid5 of the sorted
  source refs, computed by entity resolution; the canonical row itself is
  written by a *different database role* (``apply_writer``) in a different
  transaction. A physical FK would force the detection path to hold a privilege
  it is deliberately denied. The link is logical and stable by construction.

* **Money is integer, never float.** Budget and audit costs are ``microusd``
  (bigint). Domain money keeps the ``amount_cents`` integer the seed contract
  pins, and each such column carries a stored generated ``*_microusd`` sibling
  (1 cent = 10000 microusd) so both units are queryable and can never drift.
  The CRM deal amount arrives as a CRM-shaped float; staging keeps it verbatim
  as text (``amount_raw``) and normalizes to integer cents.

* **``entities`` UPDATE requires a same-transaction ``proposal_events`` row.**
  A deferred constraint trigger enforces the design rule that the apply path
  writes its reversal record in the same transaction as the canonical write.
  Grants say *who* may update the canonical layer; this trigger says *how*.
"""

