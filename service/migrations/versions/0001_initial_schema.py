def _create_apply_path_trigger() -> None:
    """Canonical UPDATE requires a same-transaction proposal_events row.

    Deferred to commit so the apply function may write the canonical row and
    the reversal record in either order within one transaction. SQLSTATE
    ``KS001`` is deliberately distinct from any built-in class so a test can
    assert on it and cannot pass on an unrelated error.
    """
    op.execute(
        """
        CREATE FUNCTION keystone_require_proposal_event() RETURNS trigger
        LANGUAGE plpgsql AS $$
        BEGIN
            IF NOT EXISTS (
                SELECT 1 FROM proposal_events
                WHERE txid = pg_current_xact_id()::text::bigint
            ) THEN
                RAISE EXCEPTION
                    'canonical UPDATE on entities requires a proposal_events row in the '
                    'same transaction (holds-before-writes)'
                    USING ERRCODE = 'KS001';
            END IF;
            RETURN NULL;
        END;
        $$;
        """
    )
    op.execute(
        """
        CREATE CONSTRAINT TRIGGER entities_require_proposal_event
        AFTER UPDATE ON entities
        DEFERRABLE INITIALLY DEFERRED
        FOR EACH ROW EXECUTE FUNCTION keystone_require_proposal_event();
        """
    )
